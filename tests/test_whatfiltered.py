def test_mullvad_killswitch_fixture():
    """Regression: real Mullvad kill-switch ruleset (captured from the
    mullvad-vm clone, Oct 2026). SSH is closed to the world but open to
    the slirp gateway inside 10/8 — the tool must agree with reality."""
    import ipaddress
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "fixture_mullvad.json")
    rs = wf.parse_nft_json(json.load(open(path)))
    rep = wf.analyze(rs)
    assert any(p["hook"] == "input" and p["policy"] == "drop"
               for p in rep["policies"])
    assert wf.resolve(rs, "tcp", 22)[0] == "DROP"
    assert wf.resolve(rs, "tcp", 22,
                      addr=ipaddress.ip_address("10.0.2.2"))[0] == "ACCEPT"


def main():
    fns = [v for k, v in sorted(globals().items())
           if k.startswith("test_") and callable(v)]
    failed = 0
    for fn in fns:
        kwargs = {}
        if "tmp_path" in fn.__code__.co_varnames[:fn.__code__.co_argcount]:
            import tempfile
            kwargs["tmp_path"] = tempfile.mkdtemp()
        try:
            fn(**kwargs)
            print("ok   %s" % fn.__name__)
        except AssertionError as exc:
            failed += 1
            print("FAIL %s: %s" % (fn.__name__, exc))
    print("%d/%d passed" % (len(fns) - failed, len(fns)))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
