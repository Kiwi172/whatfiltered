IPT_BASIC = """# Generated by iptables-save v1.8.10 (nf_tables)
*filter
:INPUT DROP [30:3256]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [10:100]
:app - [0:0]
-A INPUT -i lo -j ACCEPT
-A INPUT -p tcp -m tcp --dport 8080 -m conntrack --ctstate NEW -j ACCEPT
-A INPUT -p tcp -m tcp --dport 8080 -m conntrack --ctstate NEW -j DROP
-A INPUT -j app
-A app -p udp -m udp --dport 5353 -j ACCEPT
COMMIT
"""


def _nft(doc):
    return wf.parse_nft_json(json.loads(json.dumps(doc)))


def test_nft_policies():
    rs = _nft(NFT_BASIC)
    rep = wf.analyze(rs)
    pol = {(p["hook"], p["policy"]) for p in rep["policies"]}
    assert ("input", "drop") in pol
    assert ("output", "accept") in pol


def test_nft_reachable():
    rs = _nft(NFT_BASIC)
    rep = wf.analyze(rs)
    ports = {tuple(r["ports"]) for r in rep["reachable"]}
    assert ("22",) in ports
    assert ("53",) in ports
    scopes = {(tuple(r["ports"]), r["scope"]) for r in rep["reachable"]}
    assert (("22",), "anywhere") in scopes
    assert (("53",), "from 10.0.0.0/8") in scopes


def test_nft_shadowed():
    rs = _nft(NFT_BASIC)
    rep = wf.analyze(rs)
    assert len(rep["shadowed"]) == 1
    s = rep["shadowed"][0]
    assert "10.0.0.0/8" in s["shadowed"]
    assert "redundant" in s["note"]


def test_nft_never_matched():
    rs = _nft(NFT_BASIC)
    rep = wf.analyze(rs)
    dead = [s["rule"] for s in rep["never_matched"]]
    assert any("10.0.0.0/8" in d for d in dead)
    assert not any("dport 22 any accept" == d.split(" ", 1)[1].strip()
                   and "packets" not in d for d in dead if "dport 22" in d
                   and "10.0.0.0" not in d)


def test_nft_probes():
    rs = _nft(NFT_BASIC)
    v, why = wf.resolve(rs, "tcp", 22)
    assert v == "ACCEPT"
    v, why = wf.resolve(rs, "tcp", 443)
    assert v == "DROP" and "policy" in why
    # udp/53 is accepted only from 10.0.0.0/8: not open to anywhere...
    v, why = wf.resolve(rs, "udp", 53)
    assert v == "DROP"
    # ...but accepted from inside the allowed range
    import ipaddress
    v, why = wf.resolve(rs, "udp", 53,
                        addr=ipaddress.ip_address("10.5.0.1"))
    assert v == "ACCEPT"


def test_jump_inlining_probe():
    rs = _nft(NFT_BASIC)
    # ctdrop is a jump target; an invalid-state probe is not modeled as
    # new-connection, so tcp/22 still resolves via the accept rule.
    v, _ = wf.resolve(rs, "tcp", 22, state="new")
    assert v == "ACCEPT"


def test_iptables_parse():
    rs = wf.parse_iptables_save(IPT_BASIC)
    rep = wf.analyze(rs)
    ports = {tuple(r["ports"]) for r in rep["reachable"]}
    assert ("8080",) in ports
    assert ("5353",) in ports  # reached through the `app` jump


def test_iptables_shadowed():
    rs = wf.parse_iptables_save(IPT_BASIC)
    rep = wf.analyze(rs)
    assert any("8080" in s["shadowed"] and "drop" in s["shadowed"]
               for s in rep["shadowed"])
    # the DROP after the ACCEPT can never fire -> probe says ACCEPT
    v, why = wf.resolve(rs, "tcp", 8080)
    assert v == "ACCEPT"


def test_iptables_policy_probe():
    rs = wf.parse_iptables_save(IPT_BASIC)
    v, why = wf.resolve(rs, "tcp", 9999)
    assert v == "DROP" and "policy" in why


def test_port_range_containment():
    a = wf.Match(dports=[(1, 1024)])
    b = wf.Match(dports=[(22, 22), (80, 80)])
    assert a.shadows(b)
    assert not b.shadows(a)
    c = wf.Match(dports=[(1, 100), (101, 1024)])
    assert c.shadows(b)  # merged intervals cover 22 and 80


def test_net_containment():
    import ipaddress
    a = wf.Match(saddrs=[ipaddress.ip_network("10.0.0.0/8")])
    b = wf.Match(saddrs=[ipaddress.ip_network("10.5.0.0/16")])
    assert a.shadows(b)
    assert not b.shadows(a)


def test_opaque_blocks_shadowing():
    a = wf.Match(opaque=["weird"])
    b = wf.Match(dports=[(22, 22)])
    assert not a.shadows(b)
    assert not b.shadows(wf.Match(opaque=["x"]))


def test_return_traffic_not_reachable():
    rs = _nft(NFT_BASIC)
    rep = wf.analyze(rs)
    # the established,related jump must not appear as an inbound opening,
    # and nothing may accept all ports from anywhere
    for r in rep["reachable"]:
        assert not (r["ports"] == ["all"] and r["scope"] == "anywhere")


def test_expose_crosscheck():
    rs = _nft(NFT_BASIC)
    expose = [{"port": 22, "process": "sshd"}, {"port": 8080,
                                               "process": "vllm"}]
    rep = wf.analyze(rs, expose=expose)
    verdicts = {l["port"]: l["verdict"] for l in rep["listening"]}
    assert verdicts[22] == "ACCEPT"
    assert verdicts[8080] == "DROP"


